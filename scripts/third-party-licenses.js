// Regenerates THIRD-PARTY-LICENSES.md from the installed packages' own license files.
// Usage: npm run licenses   (run `npm install` first; re-run whenever dependencies change)
// Covers the runtime `dependencies` of package.json and their transitive dependencies, plus the
// packages in `extraPackages` (shipped in a build although they are devDependencies). The extra
// packages' own dependencies are not followed: for Electron they are install-time tooling.
// Type-only packages are skipped: they are not shipped.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(import.meta.url), '../..')
const extraPackages = ['electron']
const isTypesOnly = (name) => name.startsWith('@types/') || name === '@webgpu/types'

const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'))

// Node's resolution: look in node_modules next to the requester, then in each parent folder.
function findPackageDir (name, fromDir) {
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const candidate = join(dir, 'node_modules', name)
    if (existsSync(join(candidate, 'package.json'))) return candidate
    if (dir === root || dir === dirname(dir)) return null
  }
}

const found = new Map() // "name@version" -> { name, version, license, dir, author }
function visit (name, fromDir, followDependencies = true) {
  if (isTypesOnly(name)) return
  const dir = findPackageDir(name, fromDir)
  if (!dir) {
    console.warn(`WARN ${name}: not installed (optional dependency?), skipped`)
    return
  }
  const pkg = readJson(join(dir, 'package.json'))
  const key = `${pkg.name}@${pkg.version}`
  if (found.has(key)) return
  const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name
  found.set(key, { name: pkg.name, version: pkg.version, license: pkg.license ?? 'UNKNOWN', dir, author })
  if (followDependencies) for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir)
}

const rootPkg = readJson(join(root, 'package.json'))
for (const name of Object.keys(rootPkg.dependencies ?? {})) visit(name, root)
for (const name of extraPackages) visit(name, root, false)

